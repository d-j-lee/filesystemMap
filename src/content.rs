//! Content stage: one parallel pass over analysed text files — binary sniffing, generated
//! detection, shebangs, line/comment/complexity metrics and import extraction. Each file
//! is read at most once.

use std::path::Path;
use std::sync::atomic::{AtomicU64, Ordering};

use rayon::prelude::*;

use crate::classify::{self, ImportLang};
use crate::deps::Sources;
use crate::deps::extract::{self, Import};
use crate::model::{Category, Flags, NodeId, Tree};
use crate::strip::{self, LineStats};

#[derive(Clone, Debug)]
pub struct Options {
    /// Files larger than this are sized but not read.
    pub max_file_size: u64,
    /// Extract imports for the dependency graph.
    pub imports: bool,
}

impl Default for Options {
    fn default() -> Self {
        Options {
            max_file_size: 4 * 1024 * 1024,
            imports: true,
        }
    }
}

struct FileResult {
    id: NodeId,
    binary: bool,
    generated: bool,
    lang: Option<u16>,
    stats: LineStats,
    imports: Option<(ImportLang, Vec<Import>)>,
    manifest: Option<String>,
}

const MANIFEST_NAMES: &[&str] = &[
    "Cargo.toml",
    "package.json",
    "go.mod",
    "tsconfig.json",
    "jsconfig.json",
    "pyproject.toml",
    "setup.py",
    "setup.cfg",
];

/// Markers that identify a generated file when they appear in its header (first 5 lines).
const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "code generated by",
    "<auto-generated",
    "generated by the protocol buffer compiler",
];

/// Read and analyse every eligible file. Returns the inputs for the dependency stage.
pub fn analyse(tree: &mut Tree, root: &Path, opts: &Options, progress: &AtomicU64) -> Sources {
    let jobs: Vec<(NodeId, std::path::PathBuf)> = (0..tree.len() as NodeId)
        .filter(|&id| {
            let n = tree.get(id);
            n.is_file()
                && n.is_analysed()
                && n.bytes <= opts.max_file_size
                && (n.category.is_text() || (n.category == Category::Other && n.bytes <= 1 << 20))
        })
        .map(|id| (id, root.join(tree.rel_path(id))))
        .collect();

    for id in 0..tree.len() as NodeId {
        let n = tree.get_mut(id);
        if n.is_file() && n.is_analysed() && n.bytes > opts.max_file_size && n.category.is_text() {
            n.flags.set(Flags::TOO_LARGE);
        }
    }

    let langs: Vec<(Option<u16>, Category, bool)> = jobs
        .iter()
        .map(|(id, _)| {
            let n = tree.get(*id);
            (n.lang, n.category, n.flags.has(Flags::GENERATED))
        })
        .collect();

    let results: Vec<FileResult> = jobs
        .par_iter()
        .zip(langs.par_iter())
        .filter_map(|((id, path), &(lang, cat, generated))| {
            progress.fetch_add(1, Ordering::Relaxed);
            let bytes = std::fs::read(path).ok()?;
            Some(analyse_file(*id, path, &bytes, lang, cat, generated, opts))
        })
        .collect();

    let mut sources = Sources::default();
    for r in results {
        let n = tree.get_mut(r.id);
        if r.binary {
            n.flags.set(Flags::BINARY);
            if matches!(n.category, Category::Other | Category::Data) {
                n.category = Category::Binary;
            }
            continue;
        }
        if r.lang.is_some() && n.lang.is_none() {
            n.lang = r.lang;
            if n.category == Category::Other {
                n.category = Category::Code;
            }
        }
        if r.generated {
            n.flags.set(Flags::GENERATED);
            n.category = Category::Generated;
        }
        n.lines = sat(r.stats.lines);
        n.code = sat(r.stats.code);
        n.comments = sat(r.stats.comments);
        n.blank = sat(r.stats.blank);
        n.complexity = sat(r.stats.complexity);
        if let Some((il, imports)) = r.imports
            && !imports.is_empty()
        {
            sources.imports.push((r.id, il, imports));
        }
        if let Some(text) = r.manifest {
            sources.manifests.push((r.id, text));
        }
    }
    sources.imports.sort_by_key(|(id, _, _)| *id);
    sources.manifests.sort_by_key(|(id, _)| *id);
    sources
}

fn sat(v: u64) -> u32 {
    u32::try_from(v).unwrap_or(u32::MAX)
}

fn analyse_file(
    id: NodeId,
    path: &Path,
    bytes: &[u8],
    lang: Option<u16>,
    cat: Category,
    already_generated: bool,
    opts: &Options,
) -> FileResult {
    let mut r = FileResult {
        id,
        binary: false,
        generated: already_generated,
        lang,
        stats: LineStats::default(),
        imports: None,
        manifest: None,
    };
    let head = &bytes[..bytes.len().min(8192)];
    if memchr::memchr(0, head).is_some() {
        r.binary = true;
        return r;
    }
    if r.lang.is_none() && head.starts_with(b"#!") {
        let first = head.split(|&b| b == b'\n').next().unwrap_or(b"");
        r.lang = classify::lang_from_shebang(&String::from_utf8_lossy(first));
    }
    if !r.generated {
        r.generated = looks_generated(&bytes[..bytes.len().min(2048)], bytes);
    }

    let name = path
        .file_name()
        .map(|n| n.to_string_lossy())
        .unwrap_or_default();
    if MANIFEST_NAMES.contains(&name.as_ref()) && bytes.len() <= 512 * 1024 {
        r.manifest = Some(String::from_utf8_lossy(bytes).into_owned());
    }

    let code_like =
        r.lang.is_some_and(|l| {
            let lang = classify::lang(l);
            lang.category == Category::Code
        }) && (cat == Category::Code || cat == Category::Other || cat == Category::Generated);
    match r.lang {
        Some(l) if code_like => {
            let lang = classify::lang(l);
            let (stripped, stats) = strip::strip(bytes, &lang.syntax);
            r.stats = stats;
            if opts.imports
                && !r.generated
                && let Some(il) = lang.imports
            {
                let text = String::from_utf8_lossy(&stripped);
                r.imports = Some((il, extract::extract(il, &text)));
            }
        }
        _ => r.stats = strip::plain_stats(bytes),
    }
    r
}

fn looks_generated(head: &[u8], all: &[u8]) -> bool {
    let text = String::from_utf8_lossy(head).to_ascii_lowercase();
    for line in text.lines().take(5) {
        if GENERATED_MARKERS.iter().any(|m| line.contains(m))
            || (line.contains("generated") && line.contains("do not edit"))
            || (line.contains("this file")
                && (line.contains("generated") || line.contains("autogenerated")))
        {
            return true;
        }
    }
    // Minified: large with very long lines.
    if all.len() > 20 * 1024 {
        let lines = memchr::memchr_iter(b'\n', all).count() + 1;
        if all.len() / lines > 400 {
            return true;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_generated_and_minified() {
        assert!(looks_generated(
            b"// Code generated by protoc-gen-go. DO NOT EDIT.\n",
            b""
        ));
        assert!(looks_generated(b"# @generated by tool\n", b""));
        assert!(!looks_generated(b"fn main() {}\n", b"fn main() {}\n"));
        assert!(!looks_generated(
            b"// Please do not edit this lightly.\n",
            b""
        ));
        assert!(looks_generated(
            b"# This file is autogenerated by pip-compile\n",
            b""
        ));
        assert!(!looks_generated(
            b"/*!\nCompletions.\n\nUnlike others,\nmaintained by hand.\n2. Better than the ones that are auto-generated.\n",
            b""
        ));
        let minified = vec![b'x'; 30 * 1024];
        assert!(looks_generated(b"", &minified));
    }
}
